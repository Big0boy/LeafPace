import { RouteData } from '../types';

export function generateGpxString(route: RouteData, activityName: string = 'LeafPace Trail Loop'): string {
  const timestamp = new Date().toISOString();
  
  const trkpts = route.coordinates
    .map((pt, idx) => {
      // Simulate gentle elevation if not available
      const ele = Math.round(50 + Math.sin(idx / 5) * 12);
      return `      <trkpt lat="${pt.lat.toFixed(6)}" lon="${pt.lng.toFixed(6)}">
        <ele>${ele}</ele>
        <time>${timestamp}</time>
      </trkpt>`;
    })
    .join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<gpx version="1.1" creator="LeafPace - Touch Grass (OpenAI/WebGPU)" xmlns="http://www.topografix.com/GPX/1/1">
  <metadata>
    <name>${activityName}</name>
    <desc>Scenic nature loop generated by LeafPace with ${route.greeneryScorePercent}% greenery bias. Distance: ${route.distanceKm.toFixed(2)}km.</desc>
    <time>${timestamp}</time>
  </metadata>
  <trk>
    <name>${activityName}</name>
    <type>running</type>
    <trkseg>
${trkpts}
    </trkseg>
  </trk>
</gpx>`;
}

export function downloadGpxFile(route: RouteData, filename: string = 'leafpace_trail.gpx'): void {
  const gpxContent = generateGpxString(route);
  const blob = new Blob([gpxContent], { type: 'application/gpx+xml;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
